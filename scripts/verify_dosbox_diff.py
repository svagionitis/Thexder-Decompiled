#!/usr/bin/env python3
"""
verify_dosbox_diff.py

Compares frame-by-frame simulation traces extracted from DOSBox-X debug logs
against engine state snapshot logs generated by test_golden_replay.

Metrics validated:
- Player (x, y) coordinates
- Velocity vectors (vx, vy)
- Energy reserves
- Active entity counts
"""

import sys
import argparse
import re

def parse_trace_file(path):
    """
    Parses trace text containing lines formatted as:
    FRAME <n>: X=<x> Y=<y> VX=<vx> VY=<vy> ENERGY=<e> MODE=<m> ENT=<ent>
    """
    frames = {}
    pattern = re.compile(
        r"FRAME\s+(\d+):\s+X=([-\d]+)\s+Y=([-\d]+)\s+VX=([-\d]+)\s+VY=([-\d]+)\s+ENERGY=(\d+)\s+MODE=(\d+)"
    )

    with open(path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            match = pattern.search(line)
            if match:
                f_idx = int(match.group(1))
                frames[f_idx] = {
                    "x": int(match.group(2)),
                    "y": int(match.group(3)),
                    "vx": int(match.group(4)),
                    "vy": int(match.group(5)),
                    "energy": int(match.group(6)),
                    "mode": int(match.group(7)),
                }
    return frames

def compare_traces(dos_trace, native_trace, max_frames=None):
    dos_frames = parse_trace_file(dos_trace)
    nat_frames = parse_trace_file(native_trace)

    common_frames = sorted(set(dos_frames.keys()) & set(nat_frames.keys()))
    if max_frames:
        common_frames = common_frames[:max_frames]

    if not common_frames:
        print("[WARN] No common frame timestamps found between traces.")
        return 0

    mismatches = 0
    for f in common_frames:
        d = dos_frames[f]
        n = nat_frames[f]

        diffs = []
        for key in ["x", "y", "vx", "vy", "energy", "mode"]:
            if d[key] != n[key]:
                diffs.append(f"{key}: DOS={d[key]} vs Native={n[key]}")

        if diffs:
            mismatches += 1
            print(f"[DIFF] Frame {f}: {', '.join(diffs)}")

    total = len(common_frames)
    matched = total - mismatches
    print(f"\nTrace Comparison Summary:")
    print(f"  Total Frames Evaluated: {total}")
    print(f"  Exact Matches:          {matched} ({matched*100.0/total:.2f}%)")
    print(f"  Mismatched Frames:      {mismatches}")

    return 0 if mismatches == 0 else 1

def main():
    parser = argparse.ArgumentParser(description="Differential DOSBox trace analyzer")
    parser.add_argument("dos_trace", help="Path to DOSBox real-mode trace log")
    parser.add_argument("native_trace", help="Path to native engine trace log")
    parser.add_argument("--max-frames", type=int, default=None, help="Limit number of frames")
    args = parser.parse_args()

    sys.exit(compare_traces(args.dos_trace, args.native_trace, args.max_frames))

if __name__ == "__main__":
    main()

